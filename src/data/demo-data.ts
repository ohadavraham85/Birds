export async function loadDemoData(): Promise<number> {
  let created = 0;
  for (const [i, item] of DEMO.entries()) {
    const obs: Observation = {
      id: 'demo-' + i,
      demo: true,
      dateTime: new Date(item.d).toISOString(),
      locationName: item.loc,
      lat: item.lat,
      lng: item.lng,
      project: item.proj,
      entries: [{ species: item.sp, quantity: item.q }],
      images: [],
      notes: item.notes,
      deleted: false,
      updatedAt: '',
    };
    await saveObservation(obs);
    created++;
  }
  return created;
}

export async function removeDemoData(): Promise<number> {
  const all = await listObservationsRaw();
  let removed = 0;
  for (const o of all) {
    if (o.demo) { await deleteObservation(o.id); removed++; }
  }
  return removed;
}
